    public static (string name, double lat, double lon)? ResolveOblast(string? oblast)
    {
        if (oblast is null) return null;
        if (OblastCenter.TryGetValue(oblast.Trim(), out var c) && Of(c) is { } p)
            return (c, p.lat, p.lon);
        return null;
    }

    public static (double lat, double lon)? Of(string place)
    {
        lock (P) return P.TryGetValue(place, out var c) ? c : (P.TryGetValue(place.Trim(), out var c2) ? c2 : null);
    }

    /// Запам'ятати місце, знайдене SourceHub у повному довіднику (Cities), щоб
    /// трекер (IngestUa → Resolve) далі знаходив його точно за назвою.
    public static void Learn(string name, double lat, double lon)
    {
        lock (P) P.TryAdd(name, (lat, lon));
    }

    // Ищет координаты по названию из поста (винительный падеж: «на Полтаву», «на Українку»).
    // Сначала точное имя, затем по основе (учёт -а→-у и т.п.). Берём самое длинное совпадение.
    public static (string name, double lat, double lon)? Resolve(string? city)
    {
        if (string.IsNullOrWhiteSpace(city)) return null;
        var c = city.ToLowerInvariant().Trim().TrimEnd('.', ',', ';', ':', ')', '(', '!', '?').Trim();
        if (c.Length < 3) return null;
        (string name, double lat, double lon)? best = null;
        int bestLen = 0;
        lock (P)
        foreach (var kv in P)
        {
            var k = kv.Key.ToLowerInvariant();
            // основа: имя без последней буквы (снимает падежное окончание -а/-у/-о)
            var stem = k.Length > 4 ? k[..^1] : k;
            var cstem = c.Length > 4 ? c[..^1] : c;
            bool exact = c == k;
            bool hit = exact || c.StartsWith(stem) || k.StartsWith(cstem)
                    || (k.Contains(' ') && c.Contains(k[..Math.Min(k.Length, 6)]));
            // Точное совпадение бьёт любое частичное — иначе «на Київ» цеплялся за
            // «Київський» (район Харкова, 417 км!). Среди частичных — самое длинное.
            int score = exact ? 1000 : stem.Length;
            if (hit && score > bestLen)
            {
                best = (kv.Key, kv.Value.lat, kv.Value.lon);
                bestLen = score;
            }
        }
        return best;
    }

    // Гаверсинус: расстояние между двумя точками в км.
    public static double Km((double lat, double lon) a, (double lat, double lon) b)
    {
        const double R = 6371.0;
        double dLat = (b.lat - a.lat) * Math.PI / 180;
        double dLon = (b.lon - a.lon) * Math.PI / 180;
        double la1 = a.lat * Math.PI / 180, la2 = b.lat * Math.PI / 180;
        double h = Math.Sin(dLat / 2) * Math.Sin(dLat / 2)
                 + Math.Cos(la1) * Math.Cos(la2) * Math.Sin(dLon / 2) * Math.Sin(dLon / 2);
        return R * 2 * Math.Atan2(Math.Sqrt(h), Math.Sqrt(1 - h));
    }

    // Направление ОТ дома НА точку, в градусах (0 = север, по часовой).
    public static double Bearing((double lat, double lon) from, (double lat, double lon) to)
    {
        double la1 = from.lat * Math.PI / 180, la2 = to.lat * Math.PI / 180;
        double dLon = (to.lon - from.lon) * Math.PI / 180;
        double y = Math.Sin(dLon) * Math.Cos(la2);
        double x = Math.Cos(la1) * Math.Sin(la2) - Math.Sin(la1) * Math.Cos(la2) * Math.Cos(dLon);
        double deg = Math.Atan2(y, x) * 180 / Math.PI;
        return (deg + 360) % 360;
    }

    // Компас-подпись по градусам: Пн, ПнСх, Сх, ПдСх, Пд, ПдЗх, Зх, ПнЗх.
    public static string Compass(double deg)
    {
        string[] pts = { "Пн", "ПнСх", "Сх", "ПдСх", "Пд", "ПдЗх", "Зх", "ПнЗх" };
        return pts[(int)Math.Round(deg / 45.0) % 8];
    }

    // Скорость цели, км/ч → из неё считаем ETA. Значения приблизительные, боевые.
    public static double SpeedKmh(ThreatKind kind, string? ammo)
    {
        // Конкретний засіб зі словника (Х-101 750, Іскандер-М 7000, Кинджал 4500…).
        if (WeaponCatalog.SpeedFor(ammo) is { } known) return known;
        var a = ammo?.ToLowerInvariant() ?? "";
        return kind switch
        {
            ThreatKind.Ballistic => 4000,             // баллистика — секунды
            ThreatKind.Missile   => a.Contains("циркон") ? 6000 : 800, // крылатая ~800, Циркон гиперзвук
            ThreatKind.Kab       => 900,              // планирующая авиабомба
            ThreatKind.Aviation  => 900,              // носитель уже пускает КАБ
            ThreatKind.Drone     => a.Contains("реакт") || a.Contains("молн") ? 500 : 180, // шахед 180, реактивный ~500
            _                    => 250,
        };
    }

    // Минуты подлёта до дома по прямой (грубая оценка). null если координат нет.
    public static double? EtaMin((double lat, double lon)? pos, (double lat, double lon) home,
                                 ThreatKind kind, string? ammo)
    {
        if (pos is not { } p) return null;
        double km = Km(p, home);
        double kmh = SpeedKmh(kind, ammo);
        return kmh <= 0 ? null : km / kmh * 60.0;
    }
